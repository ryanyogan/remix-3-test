import { send, navigate, evaluate, click, type, key, waitFor, screenshot, close } from './browser-cdp.mjs'
const origin = process.env.QA_ORIGIN
if (!origin) { close(); throw Error('Set QA_ORIGIN; the Chromium test browser must be signed in.') }
let boardId
try {
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  await navigate(`${origin}/dashboard`)
  await click('.new-board-trigger')
  await waitFor('!!document.querySelector("#board-name")'); await new Promise(r=>setTimeout(r,300))
  await type('#board-name', 'Workspace browser check')
  await click('.new-board-form button[type="submit"]')
  await waitFor('location.pathname.startsWith("/dashboard/boards/") && !!document.querySelector(".add-card")')
  boardId = await evaluate('location.pathname.split("/").at(-1)')
  await click('.lane .add-card')
  await waitFor('!!document.querySelector("lexxy-editor [contenteditable]")')
  await type('[aria-label="Card title"]', 'Keep this card within reach')
  await key('Enter')
  await waitFor('!!document.querySelector(".card-open")'); await new Promise(r=>setTimeout(r,300))
  await click('.card-open')
  await waitFor('!!document.querySelector(".perma-comment-compose [contenteditable]")')
  await click('.pin-button')
  await waitFor('document.querySelector(".pin-button")?.getAttribute("aria-pressed") === "true" && !document.querySelector(".pin-button").disabled')
  await key('Escape')
  await waitFor('!!document.querySelector(".board") && document.readyState === "complete"'); await new Promise(r=>setTimeout(r,300))
  await click('[aria-label=\'Collapse column "To do"\']')
  await navigate(`${origin}/dashboard/boards/${boardId}`)
  await waitFor('!!document.querySelector(".lane[data-maybe][data-collapsed]")')
  await click('[aria-label=\'Expand column "To do"\']')
  await waitFor('!document.querySelector(".lane[data-maybe][data-collapsed]")')
  if (await evaluate('document.querySelectorAll(".card").length') !== 1) throw Error('Column duplicated its card')
  await navigate(`${origin}/dashboard`)
  await click('.dashboard-dock a[href="/dashboard?view=pinned"]')
  await waitFor('location.search === "?view=pinned" && document.readyState === "complete"'); await new Promise(r=>setTimeout(r,300))
  const link = `.activity-card[href^="/dashboard/cards/${boardId}/"]`
  await click(link)
  await waitFor('document.querySelector("#card-detail-heading")?.textContent === "Keep this card within reach" && !!document.querySelector(".perma-comment-compose [contenteditable]")')
  await key('Escape')
  await waitFor('!!document.querySelector(".board") && document.readyState === "complete"'); await new Promise(r=>setTimeout(r,300))
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await navigate(`${origin}/dashboard`)
  await waitFor('!!document.querySelector(".activity-card")')
  if (await evaluate('document.documentElement.scrollWidth > innerWidth')) throw Error('Mobile home overflows')
  await screenshot('/tmp/trellix-workspace-mobile.png')
  await click(link)
  await waitFor('!!document.querySelector(".perma-paper") && !!document.querySelector(".perma-comment-compose [contenteditable]")')
  await new Promise(resolve => setTimeout(resolve, 300))
  const bounds = await evaluate('(()=>{let r=document.querySelector(".perma-paper").getBoundingClientRect();return {left:r.left,right:r.right,width:innerWidth,documentWidth:document.documentElement.scrollWidth}})()')
  if (bounds.left < 0 || bounds.right > bounds.width || bounds.documentWidth > bounds.width) throw Error('Mobile card escapes viewport: ' + JSON.stringify(bounds))
  await screenshot('/tmp/trellix-card-mobile.png')
  await key('Escape')
  await waitFor('!!document.querySelector(".board") && document.readyState === "complete"'); await new Promise(r=>setTimeout(r,300))
  if (await evaluate('document.documentElement.scrollWidth > innerWidth')) throw Error('Mobile board overflows')
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  await navigate(`${origin}/dashboard/boards`)
  let tile = `.project-tile:has(a[href="/dashboard/boards/${boardId}"])`
  await click(`${tile} .project-delete`)
  await waitFor('!!document.querySelector(".confirm-dialog[open]")')
  await click('.confirm-dialog[open] .btn-ghost')
  if (!await evaluate(`!!document.querySelector(${JSON.stringify(tile)})`)) throw Error('Cancel removed board')
  await click(`${tile} .project-delete`)
  await click('.confirm-dialog[open] .btn-danger')
  await waitFor(`!document.querySelector(${JSON.stringify(tile)})`)
  if (await evaluate(`fetch('/dashboard/boards/${boardId}/data', {headers:{Accept:'application/json'}}).then(r=>r.status)`) !== 404) throw Error('Board deletion did not persist')
  boardId = undefined
  console.log(JSON.stringify({ createdBoard: true, pinnedCard: true, homeDeepLink: true, collapsePersisted: true, mobileBounds: true, cancelDeletion: true, confirmedDeletion: true }))
} finally {
  if (boardId) console.log('cleanup', await evaluate(`fetch('/dashboard/boards/${boardId}/delete',{method:'POST',headers:{Accept:'application/json'}}).then(r=>r.status)`))
  close()
}
