import { send, navigate, evaluate, click, type, key, waitFor, screenshot, close } from './browser-cdp.mjs'
const origin = process.env.QA_ORIGIN
if (!origin) { close(); throw Error('Set QA_ORIGIN; Chromium must be signed into a test account.') }
const ready = () => new Promise(resolve => setTimeout(resolve, 250))
async function home() { await navigate(`${origin}/dashboard`); await ready() }
async function dismiss() { await key('Escape'); await waitFor('!document.querySelector("dialog[open]")'); await ready() }
async function check(condition, message) { if (!await evaluate(condition)) throw Error(message) }
let boardId
try {
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  await home()
  await key('j', 'KeyJ')
  await waitFor('!!document.querySelector(".jump-dialog[open]")')
  await check('document.activeElement?.getAttribute("aria-label") === "Filter navigation"', 'J did not focus navigation search')
  await type('.jump-input', 'no-such-place-98765')
  await waitFor('document.querySelector(".jump-message")?.textContent.includes("Nothing matches")')
  await dismiss()
  await check('document.activeElement?.matches(".jump-trigger")', 'Escape did not return focus')
  console.log('navigation search and Escape passed')
  await key('b', 'KeyB')
  await waitFor('location.pathname === "/dashboard/boards/new" && !!document.querySelector(".new-board-form")'); await ready()
  await type('#board-name', 'Home navigation check')
  await click('.new-board-form button[type=submit]')
  await waitFor('location.pathname.startsWith("/dashboard/boards/") && !!document.querySelector(".add-card")')
  boardId = await evaluate('location.pathname.split("/").at(-1)')
  console.log('board created', boardId)
  await home()
  await key('c', 'KeyC')
  await waitFor('location.pathname === "/dashboard/cards/new" && !!document.querySelector("lexxy-editor [contenteditable]")')
  await type('#card-title', 'A card from the new home')
  await key('j', 'KeyJ')
  await check('!document.querySelector(".jump-dialog[open]")', 'Typing J opened navigation')
  await click('.perma-actions button[type=submit]')
  await waitFor('!!document.querySelector(".card-open") && location.pathname.startsWith("/dashboard/boards/")'); await ready()
  await click('.card-open')
  await waitFor('!!document.querySelector("#card-detail-heading")')
  await waitFor('!!document.querySelector(".perma-comment-compose [contenteditable]")'); await ready()
  console.log('card created')
  await click('.pin-button')
  await waitFor('document.querySelector(".pin-button")?.getAttribute("aria-pressed") === "true" && !document.querySelector(".pin-button").disabled')
  await click('.complete-button')
  await waitFor('document.querySelector(".complete-button")?.textContent.includes("Reopen") && !document.querySelector(".complete-button").disabled')
  await home()
  await check(`!!document.querySelector('.activity-column:nth-child(3) a[href^="/dashboard/cards/${boardId}/"]')`, 'Completion missing from Done')
  await key('j', 'KeyJ'); await waitFor('!!document.querySelector(".jump-dialog[open]")')
  await type('.jump-input', 'Home navigation check')
  await waitFor('document.querySelectorAll("[data-jump-link]").length === 1')
  await key('ArrowDown'); await check('document.activeElement?.hasAttribute("data-jump-link")', 'Arrow navigation did not focus result')
  await key('Enter'); await waitFor(`location.pathname === '/dashboard/boards/${boardId}'`)
  await ready(); await key('j', 'KeyJ'); await waitFor('!!document.querySelector(".jump-dialog[open]")')
  await waitFor('document.querySelector(".jump-content")?.textContent.includes("Home navigation check")')
  await key('2', 'Digit2'); await waitFor('location.search === "?view=pinned"'); await ready()
  await check(`!!document.querySelector('.activity-card[href^="/dashboard/cards/${boardId}/"]')`, 'Pinned shortcut missing pinned card')
  console.log('jump links and pins passed')
  await key('k', 'KeyK'); await waitFor('!!document.querySelector(".search-dialog[open]")'); await dismiss()
  await click(`.activity-card[href^="/dashboard/cards/${boardId}/"]`)
  await waitFor('!!document.querySelector("#card-detail-heading")')
  await home()
  await click('[aria-label="Filter activity by board"]'); await waitFor('document.querySelector("#activity-board")?.matches(":popover-open") && document.activeElement?.matches("#activity-board input")'); await key('ArrowDown'); await waitFor('!!document.querySelector("#activity-board input")?.getAttribute("aria-activedescendant")'); await key('Enter'); await waitFor('!!new URL(location.href).searchParams.get("board")'); await ready()
  await check('!!new URL(location.href).searchParams.get("board")', 'Board filter did not navigate')
  await home()
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await check('document.documentElement.scrollWidth <= innerWidth', 'Mobile home overflows')
  await screenshot('/tmp/trellix-home-mobile.png')
  await click('.jump-trigger'); await waitFor('!!document.querySelector(".jump-dialog[open]")')
  await check('(()=>{let r=document.querySelector(".jump-dialog").getBoundingClientRect();return r.left>=0 && r.right<=innerWidth && r.bottom<=innerHeight})()', 'Mobile navigation escapes viewport')
  await screenshot('/tmp/trellix-navigation-mobile.png')
  await click('.jump-close'); await waitFor('!document.querySelector(".jump-dialog[open]")'); await ready()
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  await key('j', 'KeyJ'); await waitFor('!!document.querySelector(".jump-dialog[open]")')
  // Backdrop click dismisses the menu.
  for (let type of ['mousePressed', 'mouseReleased']) await send('Input.dispatchMouseEvent', { type, x: 30, y: 200, button: 'left', clickCount: 1 })
  await waitFor('!document.querySelector(".jump-dialog[open]")')
  console.log(JSON.stringify({ jumpShortcut: true, searchAndNoResults: true, focusReturn: true, boardAndCardCreation: true, completionFeed: true, keyboardNavigation: true, lazyNavigation: true, pinnedShortcut: true, searchShortcut: true, cardDeepLink: true, boardFilter: true, mobileBounds: true, outsideDismissal: true }))
} finally {
  if (boardId) console.log('cleanup', await evaluate(`fetch('/api/v1/boards/${boardId}', {method:'DELETE'}).then(r=>r.status)`))
  close()
}
