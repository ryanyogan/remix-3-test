import { send, navigate, evaluate, click, key, waitFor, screenshot, close } from './browser-cdp.mjs'
const origin = process.env.QA_ORIGIN
if (!origin) { close(); throw Error('Set QA_ORIGIN; Chromium must be signed in.') }
const originalUrl = await evaluate('location.href')
let boardId
import { consumerRequest as request } from './browser-cdp.mjs'
const settle = () => new Promise(resolve => setTimeout(resolve, 400))
async function choose(label, text) {
  await click(`.board-quick-filter > button[aria-label=${JSON.stringify(label)}]`)
  await waitFor('!!document.querySelector(":popover-open")')
  let index = await evaluate(`[...document.querySelectorAll(':popover-open .popup-option')].findIndex(e=>e.textContent===${JSON.stringify(text)})`)
  if (index < 0) throw Error(`Missing ${label}: ${text}`)
  await click(`:popover-open .popup-option:nth-of-type(${index+1})`)
  await settle()
}
try {
  await send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 1000, deviceScaleFactor: 1, mobile: false })
  await navigate(origin + '/dashboard')
  const user = await request('/me')
  boardId = (await request('/boards','POST',{ name: 'Omarchy controls QA' })).id
  let board = await request(`/boards/${boardId}`)
  const intake = board.columns[0].id, yes = board.columns[1].id, done = board.columns[2].id
  await request(`/boards/${boardId}/columns/${yes}`, 'PATCH', { name: 'Yes', color: 'tan' })
  const review = (await request(`/boards/${boardId}/columns`, 'POST', { name: 'Review' })).id
  await request(`/boards/${boardId}/cards`, 'POST', { title: 'Assigned design card', columnId: yes, tags: ['design'], assigneeId: user.id })
  await request(`/boards/${boardId}/cards`, 'POST', { title: 'Unassigned intake card', columnId: intake, tags: ['engineering'] })
  await request(`/boards/${boardId}/cards`, 'POST', { title: 'Finished card', columnId: done })
  const url = `${origin}/dashboard/boards/${boardId}`
  await navigate(url); await settle()
  await click('[aria-label="Card filters"]'); await settle()
  if (await evaluate('document.querySelectorAll(".board-quick-filter").length') !== 7) throw Error('Missing filter pills')
  await screenshot('/tmp/trellix-board-filter-row.png')
  await choose('Tagged…', '#design')
  if (await evaluate('document.querySelectorAll(".lane .card").length') !== 1) throw Error('Tag filter failed')
  await click('.board-clear-filters')
  await choose('Assigned to…', 'No one')
  if (await evaluate('document.querySelectorAll(".lane .card").length') !== 2) throw Error('Assignment filter failed')
  await click('.board-clear-filters')
  await choose('Closed by…', user.name)
  if (await evaluate('document.querySelectorAll(".lane .card").length') !== 1) throw Error('Closer filter failed')
  await click('.board-clear-filters')
  await choose('Status…', 'Closed')
  if (await evaluate('document.querySelectorAll(".lane .card").length') !== 1) throw Error('Status filter failed')
  await click('.board-clear-filters')
  await choose('Recently updated','Oldest to newest')
  await click('.board-clear-filters')
  await click('[aria-label=\'Expand column "Yes"\']'); await settle()
  await click('[aria-label="Column options for Yes"]'); await settle()
  if (!await evaluate('document.querySelector(":popover-open button:nth-child(2)").disabled && !document.querySelector(":popover-open button:nth-child(3)").disabled')) throw Error('Incorrect boundary arrows')
  await screenshot('/tmp/trellix-board-column-menu.png')
  await key('Escape'); await waitFor('!document.querySelector(":popover-open")')
  await click('[aria-label="Column options for Yes"]')
  await click(':popover-open .popup-option:first-child'); await settle()
  if (!await evaluate('document.activeElement?.getAttribute("aria-label")==="Column name" && document.activeElement.selectionStart===0 && document.activeElement.selectionEnd===3')) throw Error('Name is not selected')
  await screenshot('/tmp/trellix-board-column-edit.png')
  await send('Input.insertText', { text: 'Ready' })
  await click(':popover-open input[aria-label="Violet"]')
  if (await evaluate('document.querySelector(":popover-open input[name=name]").value') !== 'Ready') throw Error('Color selection lost the draft name')
  await click(':popover-open .column-save'); await settle()
  await waitFor(`fetch('/dashboard/boards/${boardId}/data', {headers:{Accept:'application/json'}}).then(r=>r.json()).then(({data})=>data.columns.find(c=>c.id==='${yes}')?.color==='violet')`)
  await navigate(url); await settle()
  if (!await evaluate(`document.querySelector('[data-column-id="${yes}"]').style.getPropertyValue('--lane-color').includes('violet')`)) throw Error('Column color did not persist')
  await click('[aria-label="Column options for Ready"]')
  await click(':popover-open button:nth-child(3)'); await settle()
  board = await request(`/boards/${boardId}`)
  if (board.columns.findIndex(c=>c.id===yes) !== 2) throw Error('Move right failed')
  await click('[aria-label="Column options for Ready"]')
  if (!await evaluate('document.querySelector(":popover-open button:nth-child(3)").disabled')) throw Error('Right boundary not disabled')
  await click(':popover-open button:nth-child(2)'); await settle()
  board = await request(`/boards/${boardId}`)
  if (board.columns.findIndex(c=>c.id===yes) !== 1) throw Error('Move left failed')
  await click('[aria-label="Expand Ready into grid view"]'); await waitFor('!!document.querySelector(".board-column-view")'); await settle()
  if (await evaluate('document.querySelectorAll(".lane").length') !== 1) throw Error('Grid includes another column')
  if (await evaluate('document.querySelectorAll(".lane .card").length') !== 1) throw Error('Grid missing column card')
  await click('.board-back-link'); await waitFor('!!document.querySelector(".board:not(.board-column-view)")'); await settle()
  await click('[aria-label="Column options for Ready"]')
  await click(':popover-open button:last-child'); await waitFor('!!document.querySelector("dialog[open]")')
  await click('dialog[open] button[value="cancel"]')
  if (!(await request(`/boards/${boardId}`)).columns.some(c=>c.id===yes)) throw Error('Cancel deleted column')
  await click('[aria-label="Column options for Ready"]'); await click(':popover-open button:last-child'); await click('dialog[open] button[value="delete"]'); await settle()
  board = await request(`/boards/${boardId}`)
  if (board.columns.some(c=>c.id===yes) || board.items.find(c=>c.title==='Assigned design card')?.columnId !== intake) throw Error('Delete did not preserve cards in intake')
  // Mobile popover remains inside viewport and keyboard dismissal works.
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await navigate(url); await settle()
  await evaluate(`document.querySelector('[data-column-id="${review}"]').scrollIntoView({inline:'center',block:'nearest',behavior:'instant'})`); await settle()
  await click('[aria-label=\'Expand column "Review"\']', .5, .05); await settle()
  await click('[aria-label="Column options for Review"]'); await click(':popover-open button:first-child'); await settle()
  let rect = await evaluate('document.querySelector(":popover-open").getBoundingClientRect().toJSON()')
  if (rect.left < 0 || rect.right > 390 || rect.bottom > 844) throw Error('Mobile popup overflow')
  await screenshot('/tmp/trellix-board-column-edit-mobile.png')
  await key('Escape'); await waitFor('!document.querySelector(":popover-open")')
  console.log(JSON.stringify({ filters:true, menu:true, colorAndNamePersist:true, reorder:true, grid:true, safeDelete:true, mobile:true }))
} finally {
  if (boardId) await request(`/boards/${boardId}`, 'DELETE')
  await evaluate(`Object.keys(localStorage).filter(k=>k.startsWith('trellix:column:'+${JSON.stringify(boardId)}+':')).forEach(k=>localStorage.removeItem(k))`)
  await send('Emulation.clearDeviceMetricsOverride')
  await navigate(originalUrl)
  close()
}
