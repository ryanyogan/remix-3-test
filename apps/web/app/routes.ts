import { form, get, post, route } from 'remix/routes'

export const routes = route({
  assets: get('/assets/*path'),
  home: '/',
  apiGuide: get('/api'),
  login: form('/login'),
  logout: post('/logout'),
  theme: post('/theme'),
  signup: form('/signup'),
  dashboard: route('/dashboard', {
    index: get('/'),
    activity: get('/activity'),
    activityDay: get('/activity/day'),
    activityMore: get('/activity/more'),
    account: get('/account'),
    navigation: get('/navigation'),
    search: get('/search'),
    tokens: route('/account/tokens', {
      index: get('/'),
      create: post('/'),
      revoke: post('/:tokenId/revoke'),
    }),
    uploads: route('/uploads', {
      create: post('/'),
      discard: post('/:fileId/discard'),
      file: get('/:fileId'),
    }),
    notifications: get('/notifications'),
    insights: get('/insights'),
    cards: route('/cards', {
      new: get('/new'),
      show: get('/:boardId/:cardId'),
      data: get('/:boardId/:cardId/data'),
      create: post('/:boardId'),
      update: post('/:boardId/:cardId'),
      destroy: post('/:boardId/:cardId/delete'),
      cover: get('/:boardId/:cardId/cover'),
      setCover: post('/:boardId/:cardId/cover'),
      removeCover: post('/:boardId/:cardId/cover/delete'),
      uploadFile: post('/:boardId/:cardId/files'),
      addStep: post('/:boardId/:cardId/steps'),
      updateStep: post('/:boardId/:cardId/steps/:stepId'),
      removeStep: post('/:boardId/:cardId/steps/:stepId/delete'),
      addComment: post('/:boardId/:cardId/comments'),
      removeComment: post('/:boardId/:cardId/comments/:commentId/delete'),
    }),
    boards: route('/boards', {
      index: get('/'),
      create: post('/'),
      new: get('/new'),
      options: get('/options'),
      data: get('/:boardId/data'),
      watch: post('/:boardId/watch'),
      moveColumn: post('/:boardId/columns/:columnId/position'),
      show: get('/:boardId'),
      edit: get('/:boardId/edit'),
      webhooks: get('/:boardId/webhooks'),
      rename: post('/:boardId'),
      destroy: post('/:boardId/delete'),
      // Create and rename share one upsert so a rename can follow a still-pending create.
      upsertColumn: post('/:boardId/columns'),
      deleteColumn: post('/:boardId/columns/:columnId/delete'),
      // Create and move share one upsert, as in Trellix, so a drag can follow a pending create.
      upsertItem: post('/:boardId/items'),
      deleteItem: post('/:boardId/items/:itemId/delete'),
      uploadFile: post('/:boardId/items/:itemId/files'),
      file: get('/:boardId/files/:fileId'),
      deleteFile: post('/:boardId/files/:fileId/delete'),
    }),
  }),
})
